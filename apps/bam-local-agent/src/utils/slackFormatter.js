// Turns a normalized event plan (ragService.normalizeEventPlan) into Slack Block Kit blocks and into plain text.
// The plain text is the message's notification fallback in Slack and is also what the web pages copy and download.
// Block Kit limits respected here: 50 blocks, header 150 chars, section text 3000, 10 fields of 2000 each.

const PLACEHOLDER_RE = /\[(Confirm with Store|TBD Partner)\]/g;

const escape = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// Placeholders render as inline code so they stand out as "still to confirm".
const md = (s) => escape(s).replace(PLACEHOLDER_RE, '`[$1]`');
const cut = (s, max) => (s.length > max ? `${s.slice(0, max - 1)}…` : s);

const header = (text) => ({ type: 'header', text: { type: 'plain_text', text: cut(text, 150), emoji: true } });
const divider = { type: 'divider' };
const sectionBlock = (text) => ({ type: 'section', text: { type: 'mrkdwn', text: cut(text, 3000) } });
const fieldsBlock = (pairs) => ({
  type: 'section',
  fields: pairs.filter(([, v]) => v).slice(0, 10).map(([k, v]) => ({ type: 'mrkdwn', text: cut(`*${k}*\n${md(v)}`, 2000) }))
});
const context = (text) => ({ type: 'context', elements: [{ type: 'mrkdwn', text: cut(text, 2000) }] });
const bullets = (items) => items.map((i) => `• ${md(i)}`).join('\n');

const where = (store) => [store?.city, store?.state].filter(Boolean).join(', ');

/** Slack Block Kit message for an event plan: `{ text, blocks }`, ready for chat.postMessage or a response_url. */
export function eventPlanBlocks(plan, { store, playbook } = {}) {
  const p = plan;
  const blocks = [
    header(`🧱 ${p.title}`),
    context([`📍 *${escape(store?.name ?? 'BAM store')}*`, escape(where(store)), playbook ? `Playbook ${escape(playbook.label)}` : null].filter(Boolean).join('  ·  '))
  ];
  if (p.summary) blocks.push(sectionBlock(md(p.summary)));

  blocks.push(divider, sectionBlock(`*🎯 WHAT*\n${md(p.what.concept)}${p.what.activities.length ? `\n${bullets(p.what.activities)}` : ''}`));
  if (p.what.bam_provides.length || p.what.partner_provides.length) {
    blocks.push(fieldsBlock([
      ['BAM provides', p.what.bam_provides.map((i) => `• ${i}`).join('\n')],
      ['Partner provides', p.what.partner_provides.map((i) => `• ${i}`).join('\n')]
    ]));
  }

  blocks.push(divider, sectionBlock('*📅 WHEN*'), fieldsBlock([
    ['Dates', p.when.dates], ['Time', p.when.time],
    ['Time slots', p.when.time_slots.map((s) => `• ${s}`).join('\n')]
  ]));
  if (p.when.rationale) blocks.push(context(`🗓️ ${md(p.when.rationale)}`));

  blocks.push(divider, sectionBlock('*📍 WHERE*'), fieldsBlock([
    ['Location', p.where.location], ['Address', p.where.address],
    ['Space & layout', p.where.space], ['Tables & chairs', p.where.tables_chairs]
  ]));

  blocks.push(divider, sectionBlock(`*👥 WHO*\n${bullets(p.who.audience)}`), fieldsBlock([
    ['Store contact', p.who.store_contact], ['Partner contact', p.who.partner_contact]
  ]));

  blocks.push(divider, sectionBlock(`*💡 WHY*\n${bullets(p.why.goals)}${p.why.playbook_tie_in ? `\n_Playbook:_ ${md(p.why.playbook_tie_in)}` : ''}`));

  const hm = p.how_much;
  blocks.push(divider, sectionBlock('*💰 HOW MUCH*'), fieldsBlock([
    ['Ticket price', hm.ticket_price], ['Estimated total', hm.estimated_total], ['Partner fees', hm.partner_fees]
  ]));
  if (hm.budget.length) blocks.push(sectionBlock(`*Budget*\n${hm.budget.map((b) => `• ${md(b.item)} — ${md(b.cost)}`).join('\n')}`));
  if (hm.supplies.length) blocks.push(sectionBlock(`*Store supplies*\n${bullets(hm.supplies)}`));

  if (p.next_steps.length) {
    blocks.push(divider, sectionBlock(`*📣 Next Steps for Coordination*\n${p.next_steps.map((s) => `• *${md(s.timing)}* — ${md(s.task)} _(${md(s.owner)})_`).join('\n')}`));
  }
  if (p.store_action_items.length) {
    blocks.push(divider, sectionBlock(`*✅ Action Items Needed From Store*\n${p.store_action_items.map((s) => `• ${md(s.task)} — _${md(s.owner)}, due ${md(s.due)}_`).join('\n')}`));
  }
  if (p.open_items.length) blocks.push(divider, sectionBlock(`*⚠️ To Confirm Before Publishing*\n${bullets(p.open_items)}`));
  blocks.push(context('Generated by the BAM Local Agent · Check every `[Confirm with Store]` / `[TBD Partner]` item before publishing.'));

  return { text: cut(eventPlanText(plan, { store, playbook }), 3900), blocks: blocks.slice(0, 50) };
}

/** Plain-text version of an event plan (Slack fallback text, Copy and Download on the web pages). */
export function eventPlanText(plan, { store, playbook } = {}) {
  const p = plan;
  const li = (items) => items.map((i) => `- ${i}`);
  const out = [
    p.title.toUpperCase(),
    [store?.name, where(store), playbook ? `Playbook ${playbook.label}` : null].filter(Boolean).join(' | ')
  ];
  if (p.summary) out.push('', p.summary);
  out.push('', 'WHAT', p.what.concept, ...li(p.what.activities));
  if (p.what.bam_provides.length) out.push('BAM provides:', ...li(p.what.bam_provides));
  if (p.what.partner_provides.length) out.push('Partner provides:', ...li(p.what.partner_provides));
  out.push('', 'WHEN', `Dates: ${p.when.dates}`, `Time: ${p.when.time}`);
  if (p.when.time_slots.length) out.push('Time slots:', ...li(p.when.time_slots));
  if (p.when.rationale) out.push(`Why these dates: ${p.when.rationale}`);
  out.push('', 'WHERE', `Location: ${p.where.location}`, `Address: ${p.where.address}`, `Space & layout: ${p.where.space}`, `Tables & chairs: ${p.where.tables_chairs}`);
  out.push('', 'WHO', ...li(p.who.audience), `Store contact: ${p.who.store_contact}`, `Partner contact: ${p.who.partner_contact}`);
  out.push('', 'WHY', ...li(p.why.goals));
  if (p.why.playbook_tie_in) out.push(`Playbook: ${p.why.playbook_tie_in}`);
  out.push('', 'HOW MUCH', `Ticket price: ${p.how_much.ticket_price}`, ...p.how_much.budget.map((b) => `- ${b.item}: ${b.cost}`),
    `Estimated total: ${p.how_much.estimated_total}`, `Partner fees: ${p.how_much.partner_fees}`);
  if (p.how_much.supplies.length) out.push('Store supplies:', ...li(p.how_much.supplies));
  if (p.next_steps.length) out.push('', 'NEXT STEPS FOR COORDINATION', ...p.next_steps.map((s, i) => `${i + 1}. ${s.timing} - ${s.task} (${s.owner})`));
  if (p.store_action_items.length) out.push('', 'ACTION ITEMS NEEDED FROM STORE', ...p.store_action_items.map((s) => `[ ] ${s.task} - ${s.owner}, due ${s.due}`));
  if (p.open_items.length) out.push('', 'TO CONFIRM BEFORE PUBLISHING', ...li(p.open_items));
  return out.join('\n').trim();
}
